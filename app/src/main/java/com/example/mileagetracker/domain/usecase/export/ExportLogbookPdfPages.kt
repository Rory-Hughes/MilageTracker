package com.example.mileagetracker.domain.usecase.export

import android.graphics.Canvas
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.example.mileagetracker.domain.model.VehicleAnnualSummary
import com.example.mileagetracker.util.DateFormats
import kotlin.math.max

internal fun renderCoverPage(
    pdf: PdfDocument,
    pageIndex: Int,
    prepared: PreparedLogbookExport,
    sectionSummaries: List<VehicleAnnualSummary>,
): Int {
    val page = pdf.startPage(PdfDocument.PageInfo.Builder(PDF_PAGE_WIDTH, PDF_PAGE_HEIGHT, pageIndex).create())
    val canvas = page.canvas
    val centerX = (PDF_PAGE_WIDTH / 2).toFloat()
    val left = 64f
    val bodyPaint = Paint().apply {
        textSize = 13f
        color = android.graphics.Color.DKGRAY
    }

    canvas.drawText("CRA Automobile Logbook", centerX, 110f, pdfTitlePaint())
    canvas.drawText(
        "${prepared.scopeLabel} - Tax Year ${prepared.taxYear}",
        centerX,
        145f,
        pdfSubtitlePaint(bodyPaint),
    )

    drawCoverSummarySection(
        canvas = canvas,
        prepared = prepared,
        sectionSummaries = sectionSummaries,
        left = left,
        bodyPaint = bodyPaint,
    )
    drawCoverSectionList(canvas, prepared, left, bodyPaint)
    canvas.drawText(
        "Generated by MileageTracker on ${pdfGeneratedTimestamp()}",
        left,
        PDF_PAGE_HEIGHT - 80f,
        pdfSubtlePaint(),
    )

    pdf.finishPage(page)
    return pageIndex + 1
}

private fun drawCoverSummarySection(
    canvas: Canvas,
    prepared: PreparedLogbookExport,
    sectionSummaries: List<VehicleAnnualSummary>,
    left: Float,
    bodyPaint: Paint,
) {
    canvas.drawText("Export Summary", left, 220f, pdfHeadingPaint())
    var y = 254f

    fun line(label: String, value: String) {
        canvas.drawText(label, left, y, bodyPaint)
        canvas.drawText(value, left + 220f, y, bodyPaint)
        y += 26f
    }

    line("Scope:", prepared.scopeLabel)
    line("Categories:", prepared.categorySummary)
    line(prepared.distanceLabel + ":", "%.2f km".format(prepared.totals.selectedKm))
    line("Total logged km:", "%.2f km".format(prepared.totals.totalKm))
    line(prepared.percentLabel + ":", "%.2f%%".format(prepared.totals.selectedUsePercent))
    line("Exported trips:", prepared.totals.exportedTripCount.toString())

    val totalReimbursement = sectionSummaries
        .mapNotNull { it.reimbursementDollars }
        .sum()
    if (prepared.isBusinessOnly && totalReimbursement > 0.0) {
        line("CRA reimbursement:", "$" + "%.2f".format(totalReimbursement))
    }
}

private fun drawCoverSectionList(
    canvas: Canvas,
    prepared: PreparedLogbookExport,
    left: Float,
    bodyPaint: Paint,
) {
    val sectionTitleY = 434f
    canvas.drawText("Sections", left, sectionTitleY, pdfHeadingPaint())
    val sectionNames = if (prepared.sections.isEmpty()) {
        "No qualifying trips for the selected filters."
    } else {
        prepared.sections.joinToString(", ") { it.label }
    }
    drawWrappedText(
        canvas = canvas,
        text = sectionNames,
        x = left,
        y = sectionTitleY + 30f,
        maxChars = 62,
        lineHeight = 20f,
        paint = bodyPaint,
    )
}

internal fun renderSection(
    pdf: PdfDocument,
    pageIndex: Int,
    prepared: PreparedLogbookExport,
    section: PreparedLogbookSection,
    summary: VehicleAnnualSummary?,
): Int {
    var nextPageIndex = pageIndex
    var tripOffset = 0
    val rows = max(section.trips.size, 1)

    while (tripOffset < rows) {
        renderSectionPage(
            pdf = pdf,
            pageIndex = nextPageIndex,
            prepared = prepared,
            section = section,
            summary = summary,
            tripOffset = tripOffset,
        )
        val rowsPerPage = if (tripOffset == 0) PDF_FIRST_SECTION_PAGE_ROWS else PDF_CONTINUATION_ROWS
        nextPageIndex++
        tripOffset += rowsPerPage
        if (section.trips.isEmpty()) {
            break
        }
    }

    return nextPageIndex
}

private fun renderSectionPage(
    pdf: PdfDocument,
    pageIndex: Int,
    prepared: PreparedLogbookExport,
    section: PreparedLogbookSection,
    summary: VehicleAnnualSummary?,
    tripOffset: Int,
) {
    val page = pdf.startPage(PdfDocument.PageInfo.Builder(PDF_PAGE_WIDTH, PDF_PAGE_HEIGHT, pageIndex).create())
    val canvas = page.canvas
    val isFirstPage = tripOffset == 0
    val tableStartY = if (isFirstPage) {
        renderSectionHeader(canvas, prepared, section, summary)
    } else {
        renderContinuationHeader(canvas, section.label)
        PDF_CONTINUATION_TABLE_START_Y
    }

    renderTripTableHeader(canvas, tableStartY, prepared.includeRouteDetails)
    renderTripRows(
        canvas = canvas,
        prepared = prepared,
        section = section,
        tripOffset = tripOffset,
        tableStartY = tableStartY,
    )
    if (tripOffset + rowsPerPage(isFirstPage) >= section.trips.size) {
        renderSectionFooter(
            canvas = canvas,
            prepared = prepared,
            totals = section.totals,
            y = (PDF_PAGE_HEIGHT - 60).toFloat(),
        )
    }

    pdf.finishPage(page)
}

private fun renderTripRows(
    canvas: Canvas,
    prepared: PreparedLogbookExport,
    section: PreparedLogbookSection,
    tripOffset: Int,
    tableStartY: Int,
) {
    val rowsPerPage = rowsPerPage(tripOffset == 0)
    val pageTrips = section.trips.drop(tripOffset).take(rowsPerPage)

    if (pageTrips.isEmpty()) {
        renderEmptySectionRow(canvas, tableStartY + PDF_ROW_HEIGHT)
        return
    }

    pageTrips.forEachIndexed { index, trip ->
        renderTripRow(
            canvas = canvas,
            y = (tableStartY + PDF_ROW_HEIGHT + (index * PDF_ROW_HEIGHT)).toFloat(),
            date = DateFormats.exportPdfTripDate(trip.startedAt),
            startLocation = pdfRouteLocation(prepared.includeRouteDetails, trip.startLocation),
            endLocation = pdfRouteLocation(prepared.includeRouteDetails, trip.endLocation),
            destination = pdfNormalizedLocation(trip.endLocation),
            category = trip.tripCategory.displayName,
            km = "%.2f".format(trip.distanceKm),
            includeRoute = prepared.includeRouteDetails,
            isEvenRow = (tripOffset + index) % 2 == 0,
        )
    }
}

private fun rowsPerPage(isFirstPage: Boolean): Int =
    if (isFirstPage) PDF_FIRST_SECTION_PAGE_ROWS else PDF_CONTINUATION_ROWS

private fun renderSectionHeader(
    canvas: Canvas,
    prepared: PreparedLogbookExport,
    section: PreparedLogbookSection,
    summary: VehicleAnnualSummary?,
): Int {
    val titlePaint = Paint().apply {
        typeface = Typeface.create(Typeface.DEFAULT_BOLD, Typeface.BOLD)
        textSize = 20f
        color = android.graphics.Color.BLACK
    }
    val bodyPaint = Paint().apply {
        textSize = 12f
        color = android.graphics.Color.DKGRAY
    }

    var y = 60f
    canvas.drawText(section.label, PDF_MARGIN_LEFT.toFloat(), y, titlePaint)
    y += 26f
    section.vehicle?.let { vehicle ->
        val makeModel = listOfNotNull(vehicle.make, vehicle.model).joinToString(" ")
        val metadata = buildList {
            if (makeModel.isNotBlank()) add(makeModel)
            vehicle.year?.let { add(it.toString()) }
        }.joinToString(" / ")
        if (metadata.isNotBlank()) {
            canvas.drawText(metadata, PDF_MARGIN_LEFT.toFloat(), y, bodyPaint)
            y += 22f
        }
    }

    fun line(label: String, value: String) {
        canvas.drawText("$label $value", PDF_MARGIN_LEFT.toFloat(), y, bodyPaint)
        y += 20f
    }

    line(prepared.distanceLabel + ":", "%.2f km".format(section.totals.selectedKm))
    line("Total logged km:", "%.2f km".format(section.totals.totalKm))
    line(prepared.percentLabel + ":", "%.2f%%".format(section.totals.selectedUsePercent))
    line("Exported trips:", section.totals.exportedTripCount.toString())
    if (prepared.isBusinessOnly && summary?.reimbursementDollars != null) {
        line("CRA reimbursement:", "$" + "%.2f".format(summary.reimbursementDollars))
    }

    return y.toInt() + 16
}
